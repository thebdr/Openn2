    writer = csv.writer(out)                               # the Table writer's dialect (CRLF, minimal quoting)
    for row in rows:
        if row is not rows[0] and row[db_at] == _EM_STATE_DB and row[at]:
            if pl5:
                SANCTIONED["em_state_comments"] += 1
            row = row[:at] + [""] + row[at + 1:]
        writer.writerow(row)
