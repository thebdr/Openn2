def _is_tag_table_xml(rel: str) -> bool:
    """A PL5 `<PLC>/PLC tags/<Table>.xml` (contract §9.1, since 2026-10-09) - the sanctioned new surface."""
    if not rel.startswith(_WORKSPACE) or not rel.lower().endswith(".xml"):
        return False
    parts = rel[len(_WORKSPACE):].split("/")
    return len(parts) >= 3 and parts[1] == "PLC tags"


def _check_tag_table_xml(rel: str, path: str, label: str) -> list:
    """What the sanctioned surface must still satisfy: the contract-v1 header and a well-formed
    `SW.Tags.PlcTagTable` document naming its table."""
    import xml.etree.ElementTree as ET
    try:
        text = open(path, "rb").read().decode("utf-8-sig")
    except UnicodeDecodeError:
        return [f"{label}: tag-table XML is not UTF-8: {rel}"]
    _body, headered = _strip_header(text)
    problems = [] if headered else [f"{label}: no #!openn header: {rel}"]
    try:
        root = ET.fromstring(text)
    except ET.ParseError as error:
        return problems + [f"{label}: tag-table XML is not well-formed: {rel} ({error})"]
    table = root.find("SW.Tags.PlcTagTable")
    if root.tag != "Document" or table is None or not (table.findtext("AttributeList/Name") or "").strip():
        problems.append(f"{label}: not a SW.Tags.PlcTagTable document with a table name: {rel}")
    return problems


def _check_device_types_copy(path: str, label: str) -> list:
    """The shipped DeviceTypesDatabase (C-036, since 2026-10-09) - a PL5-only file: a `hw/device-types` header
    citing the shared original, and below it the original byte for byte (the oracle's run reads the shared one)."""
    text = open(path, "rb").read().decode("utf-8")
    body, headered = _strip_header(text)
    problems = [] if headered else [f"{label}: no #!openn header on the shipped DeviceTypesDatabase"]
    if "#! kind: hw/device-types" not in text or "#! source: Shared/HardwareConfigBuilderData/DeviceTypesDatabase.csv" not in text:
        problems.append(f"{label}: the shipped DeviceTypesDatabase is no hw/device-types copy citing the shared one")
    original, _h = _strip_header(open(_SHARED_DEVICE_TYPES, "rb").read().decode("utf-8"))
    if body != original:
        problems.append(f"{label}: the shipped DeviceTypesDatabase differs from the shared original below its header")
    return problems


def _check_signal_paths(path: str, ref_coverage: str, label: str) -> list:
    """The signal-paths page (C-038, since 2026-10-10) - a PL5-only report: its embedded JSON parses and lists one
    entry per row of the coverage report (the reference's csv), every entry pointing at a node of the graph."""
    import json
    text = open(path, encoding="utf-8").read()
    m = re.search(r'<script id="data" type="application/json">(.*?)</script>', text, re.S)
    if not m:
        return [f"{label}: the signal-paths page carries no data block"]
    try:
        data = json.loads(m.group(1))
    except ValueError as error:
        return [f"{label}: the signal-paths page's data is no JSON ({error})"]
    rows = max(0, sum(1 for line in open(ref_coverage, encoding="utf-8-sig") if line.strip()) - 1)
    problems = []
    if len(data.get("signals", [])) != rows:
        problems.append(f"{label}: the signal-paths page lists {len(data.get('signals', []))} rows, the coverage report {rows}")
    if any(not 0 <= s[0] < len(data.get("nodes", [])) for s in data.get("signals", [])):
        problems.append(f"{label}: a signal-paths entry points at no node")
    return problems


def _check_areas_table(path: str, ref_signals: str, label: str) -> list:
    """The `areas` SSOT table (C-040, since 2026-10-18) - PL5-only: one row per C&E area the reference's signals
    name (`matrix_areas`), each a plain area numbered by its digits (the builtin project keeps sub-areas off: no
    parent, no part), the configured sorter area (`sorter_areas: [1]`) the only `sorter` one."""
    import csv
    import json
    def rows(p):
        with open(p, encoding="utf-8", newline="") as fh:
            return list(csv.DictReader(line for line in fh if not line.startswith("#")))
    want = []
    for r in rows(ref_signals):
        for a in json.loads(r.get("matrix_areas") or "[]"):
            if a not in want:
                want.append(a)
    got = rows(path)
    problems = []
    missing = sorted(set(want) - {a["name"] for a in got})
    if missing:
        problems.append(f"{label}: areas.csv lacks an area the signals name: {missing}")
    for a in got:
        digits = re.findall(r"\d+", a["name"])
        if a["parent"] or a["part"] or not digits or a["number"] != str(int(digits[-1])):
            problems.append(f"{label}: areas.csv row {a['name']!r} is no plain area numbered by its digits: {dict(a)}")
    if sorted(a["name"] for a in got if a["sorter"] == "yes") != ["AREA 1"]:
        problems.append(f"{label}: areas.csv sorter areas differ from the configured [1]")
    return problems


def _legacy_rel(rel: str):
    """A PL5 output path -> the frozen reference's path: the VCI-shaped workspace (contract §4) onto the
    legacy BuilderData folders (§4.1, inverted). None = a PL5-only file by design (the workspace config,
    a header sidecar) - never compared, never a difference."""
    if not rel.startswith(_WORKSPACE):
        return rel
    parts = rel[len(_WORKSPACE):].split("/")
    head, tail = parts[0], "/".join(parts[1:])
    if head == ".openn" or rel.endswith(".openn"):
        return None
    if head == "Devices & networks":
        return _WORKSPACE + "HardwareConfiguration/" + tail
    if head == "Templates":
        return _WORKSPACE + "SoftwareBlocks/CreationInfo/Templates/" + tail
    if len(parts) >= 3 and parts[1] == "Program blocks":
        name = "/".join(parts[2:])
        sub = "CreationInfo" if name.lower().endswith(".csv") else "ImportReady"
        return _WORKSPACE + f"SoftwareBlocks/{sub}/{name}"
    if len(parts) >= 3 and parts[1] == "PLC tags":
        return _WORKSPACE + "PlcTags/" + "/".join(parts[2:])
    return rel


def compare(a_root: str, b_root: str, label: str) -> list:
    """`a_root` = the PL4 reference, `b_root` = the PL5 run (its workspace paths mapped onto the legacy
    ones; every workspace file must carry the contract-v1 header)."""
    diffs = []
    a, b = _tree(a_root), {}
    for rel, path in _tree(b_root).items():
        if _is_tag_table_xml(rel):                     # the sanctioned new surface: checked, never compared
            diffs += _check_tag_table_xml(rel, path, label)
            SANCTIONED["tag_table_xml"] += 1
            continue
        if rel == _DEVICE_TYPES_COPY:                  # the shipped database: checked against its original
            diffs += _check_device_types_copy(path, label)
            SANCTIONED["device_types_copy"] += 1
            continue
        if label == "SSOT" and rel == "areas.csv":    # the area hierarchy (C-040): checked, never compared
            diffs += _check_areas_table(path, os.path.join(a_root, "signals.csv"), label)
            SANCTIONED["areas_table"] += 1
            continue
        if rel == _SIGNAL_PATHS:                       # the signal-paths page: its data checked, never compared
            diffs += _check_signal_paths(path, os.path.join(a_root, "ProjectDocumentation", "Reports",
                                                            "io_project_coverage_report.csv"), label)
            SANCTIONED["signal_paths_page"] += 1
            continue
        legacy = _legacy_rel(rel)
        if legacy is None:
            continue                                   # PL5-only by design
        if legacy in b:
            diffs.append(f"{label}: two PL5 files map onto {legacy}: {rel}")
        b[legacy] = path
    for rel in sorted(set(a) | set(b)):
        if rel not in a:
            diffs.append(f"{label}: PL5-only file {rel}")
            continue
        if rel not in b:
            diffs.append(f"{label}: PL4-only file {rel}")
            continue
        in_workspace = rel.startswith(_WORKSPACE)
        if rel.lower().endswith((".xlsx", ".xlsm")):
            if _xlsx_cells(a[rel]) != _xlsx_cells(b[rel]):
                diffs.append(f"{label}: xlsx content differs: {rel}")
            if in_workspace and not os.path.isfile(b[rel] + ".openn"):
                diffs.append(f"{label}: no .openn header sidecar beside the workbook: {rel}")
            continue
        raw_b = open(b[rel], "rb").read()
        if in_workspace:
            try:
                _text, headered = _strip_header(raw_b.decode("utf-8"))
            except UnicodeDecodeError:
                headered = False
            if not headered:
                diffs.append(f"{label}: no #!openn header: {rel}")
        da = _norm_text(_drop_em_state_comments(rel, open(a[rel], "rb").read(), pl5=False))
        db = _norm_text(_drop_em_state_comments(rel, _restamp_renamed_rows(rel, _drop_interface_descriptions(
            rel, _drop_transfer_areas(rel, raw_b))), pl5=True))
        if da != db:
            diffs.append(f"{label}: bytes differ: {rel}")
    return diffs


def regenerate() -> int:
    """Run PL4 (Pipeline4App/ beside Pipeline5App/) into the reference - text files with the repository
    root normalized to `<REPO>` so the reference is the same in every checkout."""
    if not os.path.isdir(PL4_ROOT):
        print(f"--regenerate needs a Pipeline4App/ at {PL4_ROOT}")
        return 2
    if os.path.isdir(REFERENCE):
        shutil.rmtree(REFERENCE)
    db_dir, out_dir = os.path.join(REFERENCE, "db"), os.path.join(REFERENCE, "out")
    os.makedirs(db_dir)
    os.makedirs(out_dir)
    print("running PL4 into the reference...")
    run_pl4(db_dir, out_dir)
    for path in _tree(REFERENCE).values():
        if not path.lower().endswith((".xlsx", ".xlsm")):
            data = open(path, "rb").read()
            normed = _norm_text(data)
            if normed != data:
                open(path, "wb").write(normed)
    print(f"reference written: {len(_tree(db_dir))} SSOT files + {len(_tree(out_dir))} output files -> {REFERENCE}")
    return 0


def main() -> int:
    if "--regenerate" in sys.argv[1:]:
        return regenerate()
    if not os.path.isdir(REFERENCE):
        print(f"no PL4 reference at {REFERENCE} - run with --regenerate (needs Pipeline4App/)")
        return 2
    ref_db, ref_out = os.path.join(REFERENCE, "db"), os.path.join(REFERENCE, "out")
    with tempfile.TemporaryDirectory() as tmp:
        p5db, p5out = os.path.join(tmp, "pl5", "db"), os.path.join(tmp, "pl5", "out")
        for d in (p5db, p5out):
            os.makedirs(d)
        print("running PL5 (against the frozen PL4 reference)...")
        run_pl5(p5db, p5out)
        diffs = compare(ref_db, p5db, "SSOT") + compare(ref_out, p5out, "OUTPUT")
        print(f"\ncompared {len(_tree(ref_db))} SSOT files + {len(_tree(ref_out))} output files"
              f" (+ {SANCTIONED['tag_table_xml']} sanctioned tag-table XML: header + well-formedness checked)")
        if diffs:
            print(f"PARITY BROKEN - {len(diffs)} differences:")
            for d in diffs:
                print("  ", d)
            return 1
        print("PARITY OK - 0 diffs (PL4 -> PL5 byte-identical modulo the sanctioned normalizations; "
              f"{SANCTIONED['transfer_area_rows']} PL5-only transfer-area rows, "
              f"{SANCTIONED['interface_descriptions']} interface descriptions + "
              f"{SANCTIONED['region_comments']} SCL region comments, {SANCTIONED['device_types_copy']} shipped "
              f"DeviceTypesDatabase checked against its original, {SANCTIONED['signal_paths_page']} signal-paths "
              f"page checked against the coverage rows, {SANCTIONED['areas_table']} areas table checked against "
              f"the signals' areas, {SANCTIONED['renamed_tags']} renamed name(s) read in their new spelling, "
              f"{SANCTIONED['em_state_comments']} 05_EM_STATE comments not compared)")
        return 0


